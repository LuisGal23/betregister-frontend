function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

export function getTeamLogo(teamName: string, sport?: string): string | null {
  if (!teamName) return null;
  const key = normalizeText(teamName);

  // Check sport-specific dictionaries first
  if (sport === 'Americano' || sport === 'NFL') {
    if (NFL_LOGOS[key]) return NFL_LOGOS[key];
    for (const [name, url] of Object.entries(NFL_LOGOS)) {
      if (key.includes(name) || name.includes(key)) return url;
    }
  } else if (sport === 'Básquetbol' || sport === 'NBA') {
    if (NBA_LOGOS[key]) return NBA_LOGOS[key];
    for (const [name, url] of Object.entries(NBA_LOGOS)) {
      if (key.includes(name) || name.includes(key)) return url;
    }
  } else if (sport === 'Béisbol' || sport === 'MLB') {
    if (MLB_LOGOS[key]) return MLB_LOGOS[key];
    for (const [name, url] of Object.entries(MLB_LOGOS)) {
      if (key.includes(name) || name.includes(key)) return url;
    }
  } else {
    if (SOCCER_LOGOS[key]) return SOCCER_LOGOS[key];
    for (const [name, url] of Object.entries(SOCCER_LOGOS)) {
      if (key.includes(name) || name.includes(key)) return url;
    }
  }

  // Cross-sport fallback
  const all = { ...NFL_LOGOS, ...SOCCER_LOGOS, ...NBA_LOGOS, ...MLB_LOGOS };
  if (all[key]) return all[key];
  for (const [name, url] of Object.entries(all)) {
    if (key.length >= 4 && (key.includes(name) || name.includes(key))) {
      return url;
    }
  }

  return null;
}

export function parseMatchupFromText(
  eventText: string,
  sport?: string,
): { away: string; home: string; away_logo?: string; home_logo?: string } | null {
  if (!eventText) return null;

  // Take the matchup portion before any ' · ' delimiter
  const mainPart = eventText.split(' · ')[0].split(' | ')[0].trim();

  // Try matching ' vs ' or ' vs. ' or ' v '
  let parts: string[] = [];
  if (mainPart.includes(' vs ')) {
    parts = mainPart.split(' vs ');
  } else if (mainPart.includes(' vs. ')) {
    parts = mainPart.split(' vs. ');
  } else if (mainPart.includes(' v ')) {
    parts = mainPart.split(' v ');
  } else if (mainPart.includes(' - ')) {
    parts = mainPart.split(' - ');
  }

  if (parts.length >= 2) {
    const away = parts[0].trim();
    const home = parts[1].trim();
    if (away && home) {
      return {
        away,
        home,
        away_logo: getTeamLogo(away, sport) || undefined,
        home_logo: getTeamLogo(home, sport) || undefined,
      };
    }
  }

  return null;
}
